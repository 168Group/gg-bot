import { test, expect } from '@playwright/test';
test('staff can browse fixtures, replay refreshes and see safe draft guidance', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/auth/demo');
  await page.getByRole('link', { name: /^Modules/ }).click();
  const card = page.locator('article').filter({ has: page.getByRole('heading', { name: 'GottaGacha events', exact: true }) });
  await expect(card).toBeVisible();
  if (await card.getByRole('button', { name: 'Enable', exact: true }).count()) await card.getByRole('button', { name: 'Enable', exact: true }).click();
  await expect(card.getByText('Active', { exact: true })).toBeVisible({ timeout: 15000 });
  await card.getByRole('link', { name: 'Open module' }).click();
  await expect(page.getByRole('heading', { name: 'A little more to look forward to.' })).toBeVisible();
  await page.getByLabel('Event source').selectOption('fixtures');
  await page.waitForResponse(response => response.url().endsWith('/api/modules/gottagacha-events/settings'));
  await expect(page.getByLabel('Event source')).toHaveValue('fixtures');
  await page.getByRole('button', { name: 'Save event settings' }).click();
  const refresh = page.getByRole('button', { name: 'Refresh sample events' });
  await expect(refresh).toBeEnabled({ timeout: 15000 }); await refresh.click();
  await expect(page.getByText(/Job completed: Fixture refresh complete/)).toBeVisible({ timeout: 15000 });
  await expect(page.getByRole('heading', { name: 'Sample community game night', exact: true })).toBeVisible();
  await expect(page.locator('.gg-preview-grid article')).toHaveCount(3);
  const secondRequest = page.waitForResponse(response => response.url().endsWith('/api/modules/gottagacha-events/refresh-fixtures') && response.request().method() === 'POST');
  await refresh.click();
  const secondJob = (await (await secondRequest).json()).data.id as string;
  await page.waitForResponse(response => response.url().endsWith(`/api/jobs/${secondJob}`));
  await expect(refresh).toBeEnabled({ timeout: 15000 });
  await expect(page.getByText(/Job completed: Fixture refresh complete. 0 new/)).toBeVisible({ timeout: 15000 });
  await expect(page.locator('.gg-preview-grid article')).toHaveCount(3);
  await expect(page.getByText('Publishing unavailable', { exact: true })).toBeVisible();
  await expect(page.getByText('Never sent', { exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= (visualViewport?.width ?? innerWidth) + 1)).toBe(true);
  await page.screenshot({ path: `test-results/gg-events-${test.info().project.name}.png`, fullPage: true });
  await page.reload(); await expect(page.getByLabel('Event source')).toHaveValue('fixtures');
  await page.getByLabel('Event source').selectOption('disconnected');
  await page.getByRole('button', { name: 'Save event settings' }).click();
  await expect(refresh).toBeDisabled();
  await expect(page.getByRole('heading', { name: 'Sample community game night', exact: true })).toHaveCount(0);
  expect(errors).toEqual([]);
});
